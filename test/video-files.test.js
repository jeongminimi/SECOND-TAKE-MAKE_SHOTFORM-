'use strict';
/**
 * Choosing a video the operator already has.
 *
 * storage/video holds the files they put there by hand. Before this, the only way to attach one was
 * to upload it through the browser — into the folder it was already in. The listing exists so that
 * stops being necessary, which means the one thing that really matters is that a `file_ref` from
 * this list is the exact shape `saveClipAsset` already accepts.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { makeEnv, count } = require('./helpers');
const entry = require('../src/ingest/manualEntry');
const { createApp } = require('../src/web/server');
const { fromStoredPath } = require('../src/config');

const PUBLISHED = '2026-11-20T09:00:00Z';

/** A video folder of our own, so the test never depends on what is really in storage/video. */
async function envWithVideos(files) {
  const env = await makeEnv({}, { seed: false });
  const dir = path.join(env.dir, 'videofolder');
  fs.mkdirSync(dir, { recursive: true });
  for (const [name, body] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), body);
  env.cfg.resolved.video = dir;
  env.videoDir = dir;
  return env;
}

function buildCandidate(db) {
  const channel = entry.saveChannel(db, { platform: 'youtube', external_id: 'UC-VF', name: 'Video Files Official (TEST)', is_test: 1 }).row;
  const video = entry.saveVideo(db, {
    channel_id: channel.id, platform: 'youtube', platform_video_id: 'VF-0001',
    official_url: 'https://www.example.com/watch?v=VF-0001', title: 'NOVA – Paper Lantern (Live Band Version)', published_at: PUBLISHED,
  }).row;
  const track = entry.saveTrack(db, { track_key: 'TR_VF', original_artist_en: 'NOVA', title_en: 'Paper Lantern', name_evidence: 'TEST: official title' }).row;
  return entry.saveCandidate(db, {
    candidate_key: 'P700-vf', source_video_id: video.id, track_id: track.id,
    performer_en: 'NOVA', performance_type: 'live', arrangement_tags: ['band'],
    version_evidence: 'TEST: "Live Band Version" stated in the official title',
  }).row;
}

test('video files: only video files are listed, newest first', async () => {
  const { cfg } = await envWithVideos({
    'a-stage.mp4': 'x', 'b-clip.MOV': 'x', 'c.mkv': 'x', 'd.webm': 'x',
    'notes.txt': 'x', 'cover.jpg': 'x', 'app.db': 'x', 'script.js': 'x',
  });
  const names = entry.listVideoFiles(cfg).map((f) => f.name).sort();
  assert.deepEqual(names, ['a-stage.mp4', 'b-clip.MOV', 'c.mkv', 'd.webm'], 'extension decides, case does not');

  for (const f of entry.listVideoFiles(cfg)) {
    assert.ok(f.bytes >= 0 && f.mtime && f.file_ref, `${f.name} is missing a field the screen shows`);
  }
  // newest first
  const list = entry.listVideoFiles(cfg);
  for (let i = 1; i < list.length; i++) assert.ok(list[i - 1].mtime >= list[i].mtime, 'sorted by last modified, descending');
});

test('video files: a listed file_ref is accepted by the clip form exactly as it comes back', async () => {
  const { db, cfg, ffmpeg } = await envWithVideos({});
  if (!ffmpeg) return; // the sample clip is generated by FFmpeg
  // a real, playable video so the whole path is exercised, not just the string shape
  fs.copyFileSync(path.join(cfg.resolved.testAssets, 'sample_live_clip.mp4'), path.join(cfg.resolved.video, '내 무대 영상.mp4'));

  const [file] = entry.listVideoFiles(cfg);
  assert.ok(file, 'the folder has one video in it');
  assert.ok(fs.existsSync(fromStoredPath(cfg, file.file_ref)), 'file_ref resolves back to the file on disk');

  const candidate = buildCandidate(db);
  const saved = entry.saveClipAsset(db, cfg, {
    candidate_id: candidate.id, file_ref: file.file_ref,       // ← straight from the list, untouched
    source_start_sec: '0:20', source_end_sec: '0:45', personal_use_only: 1,
  });
  assert.equal(saved.row.file_ref, file.file_ref, 'stored exactly as listed — no second copy, no rewriting');

  // and the same shape the upload path produces
  const uploaded = entry.storeClipFile(cfg, 'uploaded.mp4', Buffer.from('bytes'));
  const shape = (s) => (path.isAbsolute(s) ? 'absolute' : 'project-relative with forward slashes');
  assert.equal(shape(file.file_ref), shape(uploaded.file_ref), 'both paths are written the same way');
});

test('video files: the route lists, refuses to look elsewhere, and writes nothing', async () => {
  const { db, cfg, dir } = await envWithVideos({ 'one.mp4': 'x', 'two.mp4': 'x', 'readme.txt': 'x' });
  // something outside the folder that must never be reachable
  fs.writeFileSync(path.join(dir, 'outside.mp4'), 'x');

  const tables = ['source_channels', 'source_videos', 'tracks', 'performance_candidates', 'clip_assets', 'usage_permissions', 'reels'];
  const before = tables.map((t) => [t, count(db, t)]);

  const server = http.createServer(createApp(cfg, db));
  await new Promise((r) => server.listen(0, r));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const r = await (await fetch(`${base}/api/entry/video-files`)).json();
    assert.equal(r.ok, true);
    assert.deepEqual(r.files.map((f) => f.name).sort(), ['one.mp4', 'two.mp4']);
    assert.ok(!r.files.some((f) => f.name === 'outside.mp4'), 'the folder above is not part of the list');
    assert.ok(!r.files.some((f) => /\.\./.test(f.file_ref)), 'no file_ref climbs out of the folder');

    // query parameters are not a way to point it somewhere else
    const poke = await (await fetch(`${base}/api/entry/video-files?dir=${encodeURIComponent(dir)}&path=../`)).json();
    assert.deepEqual(poke.files.map((f) => f.name).sort(), ['one.mp4', 'two.mp4'], 'the folder is fixed by config, not by the request');

    for (const [t, n] of before) assert.equal(count(db, t), n, `${t} must not change`);
  } finally {
    server.close();
  }
});

test('video files: an empty or missing folder is an empty list, not an error', async () => {
  const { db, cfg } = await envWithVideos({});
  const server = http.createServer(createApp(cfg, db));
  await new Promise((r) => server.listen(0, r));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const empty = await (await fetch(`${base}/api/entry/video-files`)).json();
    assert.equal(empty.ok, true);
    assert.deepEqual(empty.files, []);

    fs.rmSync(cfg.resolved.video, { recursive: true, force: true });
    const gone = await (await fetch(`${base}/api/entry/video-files`)).json();
    assert.equal(gone.ok, true, 'a folder that does not exist yet is not a failure');
    assert.deepEqual(gone.files, []);
  } finally {
    server.close();
  }
});
